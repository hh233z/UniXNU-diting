#!/usr/bin/env python3
"""Emit the /private/var directory skeleton of a mounted Apple OS volume and insert it into the base XNU patch.

The Data volume ships empty, while iOS expects the skeleton a restore normally writes
(/private/var/{db,mobile,folders,tmp,log,...}) with specific owners and modes. The matching OS volume
carries that skeleton, so the kernel recreates it on first boot instead of needing a Data image
prepared on macOS. Only directory metadata is emitted - no file contents.

Usage:
    gen-var-skeleton.py --source <mounted OS root>/private/var [--depth 2] [--exclude staged_apps]
        [--out table.c] [--insert-into patches/xnu-ipados18/0001-diting-darwin24.patch]

The code is inserted into the base patch (not a follow-up patch) because line numbers shift as the
series applies and a follow-up hunk cannot be anchored reliably.
"""
import argparse
import os
import re
import sys
from pathlib import Path

ANCHOR = '+\tif (!error) native_owner_data_stage = 4;'


def collect(root, depth, excludes):
    entries = []
    for current, dirs, _files in os.walk(root, followlinks=False):
        rel = Path(current).relative_to(root)
        if len(rel.parts) > depth:
            dirs[:] = []
            continue
        dirs[:] = sorted(d for d in dirs if d not in excludes)
        if not rel.parts:
            continue
        st = os.lstat(current)
        entries.append((str(rel), st.st_mode & 0o7777, int(st.st_uid), int(st.st_gid)))
    entries.sort()
    return entries


def table_lines(entries, indent):
    lines = [indent + '/* generated by scripts/gen-var-skeleton.py; metadata only */']
    lines.append(indent + 'static const struct pong_var_dir pong_var_skeleton[] = {')
    for path, mode, uid, gid in entries:
        lines.append(f'{indent}    {{"{path}", 0{mode:o}, {uid}, {gid}}},')
    lines.append(indent + '};')
    return lines


def replacement(entries, indent='\t\t'):
    lines = ['\tif (!error) {',
             '\t\tnative_owner_data_stage = 4;',
             indent + 'struct pong_var_dir { const char *rel; unsigned short mode; unsigned int uid, gid; };']
    lines += table_lines(entries, indent)
    lines += [
        indent + 'int created = 0, failed = 0;',
        indent + 'for (unsigned index = 0; index < sizeof(pong_var_skeleton) / sizeof(pong_var_skeleton[0]); ++index) {',
        indent + '\tconst struct pong_var_dir *entry = &pong_var_skeleton[index];',
        indent + '\tchar path[256];',
        indent + '\tint length = snprintf(path, sizeof(path), "/private/var/%s", entry->rel);',
        indent + '\tif (length <= 0 || length >= (int)sizeof(path)) { failed++; continue; }',
        indent + '\tuser_addr_t target = scratch + 0x400;',
        indent + '\tif (copyout(path, target, length + 1)) { failed++; continue; }',
        indent + '\tstruct mkdir_args create = { .path = target, .mode = entry->mode };',
        indent + '\tint entry_error = mkdir(p, &create, &result);',
        indent + '\tif (entry_error == EEXIST) { created++; continue; }',
        indent + '\tif (entry_error) { failed++; continue; }',
        indent + '\tstruct chmod_args access = { .path = target, .mode = entry->mode };',
        indent + '\tchmod(p, &access, &result);',
        indent + '\tstruct chown_args owner = { .path = target, .uid = entry->uid, .gid = entry->gid };',
        indent + '\tchown(p, &owner, &result);',
        indent + '\tcreated++;',
        indent + '}',
        indent + 'printf("DITING APFS: var skeleton created=%d failed=%d\\n", created, failed);',
        '\t}',
    ]
    return lines


def insert_into(entries, patch):
    text = patch.read_text()
    lines = text.splitlines()
    index = next((i for i, line in enumerate(lines) if line == ANCHOR), None)
    if index is None:
        raise SystemExit(f'{patch}: anchor line not found')
    added = ['+' + line for line in replacement(entries)]
    lines[index:index + 1] = added
    for position in range(index, -1, -1):
        match = re.match(r'@@ -(\d+),(\d+) \+(\d+),(\d+) @@', lines[position])
        if match:
            old_start, old_count, new_start, new_count = (int(x) for x in match.groups())
            new_count += len(added) - 1
            lines[position] = f'@@ -{old_start},{old_count} +{new_start},{new_count} @@'
            break
    else:
        raise SystemExit(f'{patch}: hunk header not found above the anchor')
    patch.write_text('\n'.join(lines) + '\n')
    print(f'{patch}: inserted {len(added)} lines ({len(entries)} directories)', file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--depth', type=int, default=2)
    parser.add_argument('--exclude', action='append', default=[])
    parser.add_argument('--out', type=Path)
    parser.add_argument('--insert-into', type=Path)
    args = parser.parse_args()
    entries = collect(args.source.resolve(), args.depth, args.exclude)
    if args.insert_into:
        insert_into(entries, args.insert_into)
    else:
        text = '\n'.join(table_lines(entries, ''))
        if args.out:
            args.out.write_text(text + '\n')
        else:
            print(text)


if __name__ == '__main__':
    main()